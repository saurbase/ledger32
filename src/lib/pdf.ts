import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import {
  ACCOUNT_TYPES,
  ACCOUNT_TYPE_LABELS,
  formatMoney,
  round2,
  type Account,
  type JournalEntry,
  type BalanceSheet,
  type IncomeStatement,
} from "@/lib/types";

const ORANGE: [number, number, number] = [249, 115, 22]; // #f97316
const BLACK: [number, number, number] = [10, 10, 10];
const GRAY: [number, number, number] = [110, 110, 110];
const LIGHT: [number, number, number] = [245, 245, 245];

function header(doc: jsPDF, title: string, subtitle?: string) {
  const pageWidth = doc.internal.pageSize.getWidth();

  // Orange accent bar
  doc.setFillColor(...ORANGE);
  doc.rect(14, 14, 4, 14, "F");

  // Brand
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(...BLACK);
  doc.text("LEDGER", 22, 21);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(...GRAY);
  doc.text("Double-Entry Bookkeeping", 22, 26.5);

  // Report title (right aligned)
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(...BLACK);
  doc.text(title, pageWidth - 14, 20, { align: "right" });

  if (subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...GRAY);
    doc.text(subtitle, pageWidth - 14, 26, { align: "right" });
  }

  return 34; // top margin for table
}

function footer(doc: jsPDF) {
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setDrawColor(...LIGHT);
    doc.setLineWidth(0.3);
    doc.line(14, pageHeight - 14, pageWidth - 14, pageHeight - 14);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...GRAY);
    doc.text(
      "Generated by Ledger · " + new Date().toLocaleString(),
      14,
      pageHeight - 9
    );
    doc.text(
      `Page ${i} of ${pageCount}`,
      pageWidth - 14,
      pageHeight - 9,
      { align: "right" }
    );
  }
}

function money(n: number): string {
  return formatMoney(n);
}

export function exportTrialBalance(
  rows: { account: { code: string; name: string }; debit: number; credit: number }[],
  dateLabel: string
) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const top = header(doc, "Trial Balance", `As of ${dateLabel}`);

  const totalDebit = round2(rows.reduce((s, r) => s + r.debit, 0));
  const totalCredit = round2(rows.reduce((s, r) => s + r.credit, 0));

  autoTable(doc, {
    startY: top,
    head: [["Code", "Account", "Debit", "Credit"]],
    body: rows.map((r) => [
      r.account.code,
      r.account.name,
      r.debit ? money(r.debit) : "—",
      r.credit ? money(r.credit) : "—",
    ]),
    foot: [
      [
        { content: "Totals", colSpan: 2, styles: { halign: "right" } },
        money(totalDebit),
        money(totalCredit),
      ],
    ],
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5 },
    headStyles: {
      fillColor: BLACK,
      textColor: 255,
      fontStyle: "bold",
      halign: "left",
    },
    footStyles: { fillColor: LIGHT, textColor: BLACK, fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: 22 },
      2: { halign: "right", cellWidth: 40 },
      3: { halign: "right", cellWidth: 40 },
    },
    didParseCell: (data) => {
      if (data.section === "foot") {
        data.cell.styles.fontStyle = "bold";
      }
    },
  });

  // Balance check note
  const finalY = (doc as any).lastAutoTable.finalY + 8;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  const balanced = round2(totalDebit - totalCredit) === 0;
  doc.setTextColor(balanced ? 22 : 200, balanced ? 120 : 40, 22);
  doc.text(
    balanced ? "✓ Debits equal credits — books are balanced." : "⚠ Debits and credits do not match.",
    14,
    finalY
  );

  footer(doc);
  doc.save(`trial-balance-${dateLabel}.pdf`);
}

export function exportIncomeStatement(
  is: IncomeStatement,
  dateLabel: string
) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const top = header(doc, "Income Statement", `For period ending ${dateLabel}`);

  autoTable(doc, {
    startY: top,
    head: [["Code", "Revenue Account", "Amount"]],
    body: is.revenue.map((r) => [
      r.account.code,
      r.account.name,
      money(r.amount),
    ]),
    foot: [[
      { content: "Total Revenue", colSpan: 2, styles: { halign: "right" } },
      money(is.totalRevenue),
    ]],
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5 },
    headStyles: { fillColor: BLACK, textColor: 255, halign: "left" },
    footStyles: { fillColor: LIGHT, textColor: BLACK },
    columnStyles: { 0: { cellWidth: 22 }, 2: { halign: "right", cellWidth: 45 } },
  });

  let y = (doc as any).lastAutoTable.finalY + 10;

  autoTable(doc, {
    startY: y,
    head: [["Code", "Expense Account", "Amount"]],
    body: is.expenses.map((r) => [
      r.account.code,
      r.account.name,
      money(r.amount),
    ]),
    foot: [[
      { content: "Total Expenses", colSpan: 2, styles: { halign: "right" } },
      money(is.totalExpenses),
    ]],
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5 },
    headStyles: { fillColor: BLACK, textColor: 255, halign: "left" },
    footStyles: { fillColor: LIGHT, textColor: BLACK },
    columnStyles: { 0: { cellWidth: 22 }, 2: { halign: "right", cellWidth: 45 } },
  });

  y = (doc as any).lastAutoTable.finalY + 10;

  // Net income summary box
  doc.setFillColor(...ORANGE);
  doc.rect(14, y, doc.internal.pageSize.getWidth() - 28, 14, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(255, 255, 255);
  doc.text("NET INCOME", 18, y + 9);
  doc.text(money(is.netIncome), doc.internal.pageSize.getWidth() - 18, y + 9, {
    align: "right",
  });

  footer(doc);
  doc.save(`income-statement-${dateLabel}.pdf`);
}

export function exportBalanceSheet(bs: BalanceSheet, dateLabel: string) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const top = header(doc, "Balance Sheet", `As of ${dateLabel}`);

  autoTable(doc, {
    startY: top,
    head: [["Code", "Assets", "Amount"]],
    body: bs.assets.map((r) => [r.account.code, r.account.name, money(r.amount)]),
    foot: [[
      { content: "Total Assets", colSpan: 2, styles: { halign: "right" } },
      money(bs.totalAssets),
    ]],
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5 },
    headStyles: { fillColor: BLACK, textColor: 255, halign: "left" },
    footStyles: { fillColor: LIGHT, textColor: BLACK },
    columnStyles: { 0: { cellWidth: 22 }, 2: { halign: "right", cellWidth: 45 } },
  });

  let y = (doc as any).lastAutoTable.finalY + 10;

  autoTable(doc, {
    startY: y,
    head: [["Code", "Liabilities", "Amount"]],
    body: bs.liabilities.map((r) => [r.account.code, r.account.name, money(r.amount)]),
    foot: [[
      { content: "Total Liabilities", colSpan: 2, styles: { halign: "right" } },
      money(bs.totalLiabilities),
    ]],
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5 },
    headStyles: { fillColor: BLACK, textColor: 255, halign: "left" },
    footStyles: { fillColor: LIGHT, textColor: BLACK },
    columnStyles: { 0: { cellWidth: 22 }, 2: { halign: "right", cellWidth: 45 } },
  });

  y = (doc as any).lastAutoTable.finalY + 10;

  // Equity section including net income
  const equityRows = bs.equity.map((r) => [
    r.account.code,
    r.account.name,
    money(r.amount),
  ]);
  if (round2(bs.netIncome) !== 0) {
    equityRows.push(["—", "Net Income (current period)", money(bs.netIncome)]);
  }

  autoTable(doc, {
    startY: y,
    head: [["Code", "Equity", "Amount"]],
    body: equityRows,
    foot: [[
      { content: "Total Equity", colSpan: 2, styles: { halign: "right" } },
      money(bs.totalEquity),
    ]],
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5 },
    headStyles: { fillColor: BLACK, textColor: 255, halign: "left" },
    footStyles: { fillColor: LIGHT, textColor: BLACK },
    columnStyles: { 0: { cellWidth: 22 }, 2: { halign: "right", cellWidth: 45 } },
  });

  y = (doc as any).lastAutoTable.finalY + 8;

  doc.setFillColor(...BLACK);
  doc.rect(14, y, doc.internal.pageSize.getWidth() - 28, 16, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(255, 255, 255);
  doc.text(
    `Liabilities + Equity:  ${money(bs.totalLiabilities + bs.totalEquity)}`,
    18,
    y + 6.5
  );
  doc.text(`Total Assets:  ${money(bs.totalAssets)}`, 18, y + 12.5);
  const right = doc.internal.pageSize.getWidth() - 18;
  doc.setTextColor(...ORANGE);
  doc.text(bs.balanced ? "BALANCED" : "OUT OF BALANCE", right, y + 6.5, {
    align: "right",
  });

  footer(doc);
  doc.save(`balance-sheet-${dateLabel}.pdf`);
}

interface LedgerForExport {
  account: { code: string; name: string };
  lines: {
    date: string;
    description: string;
    reference?: string | null;
    debit: number;
    credit: number;
    runningBalance: number;
    isReversal: boolean;
  }[];
  totalDebit: number;
  totalCredit: number;
  closingBalance: number;
}

export function exportGeneralLedger(ledgers: LedgerForExport[], dateLabel: string) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const top = header(doc, "General Ledger", `Through ${dateLabel}`);

  let y = top;
  for (const l of ledgers) {
    if (y > doc.internal.pageSize.getHeight() - 40) {
      doc.addPage();
      y = 20;
    }

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(...BLACK);
    doc.text(`${l.account.code} · ${l.account.name}`, 14, y);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...GRAY);
    doc.text(
      `Closing balance: ${money(l.closingBalance)}`,
      doc.internal.pageSize.getWidth() - 14,
      y,
      { align: "right" }
    );
    y += 3;

    autoTable(doc, {
      startY: y,
      head: [["Date", "Description", "Ref", "Debit", "Credit", "Balance"]],
      body: l.lines.map((ln) => [
        ln.date,
        ln.description + (ln.isReversal ? " (reversal)" : ""),
        ln.reference ?? "",
        ln.debit ? money(ln.debit) : "—",
        ln.credit ? money(ln.credit) : "—",
        money(ln.runningBalance),
      ]),
      foot: [[
        { content: "Totals", colSpan: 3, styles: { halign: "right" } },
        money(l.totalDebit),
        money(l.totalCredit),
        money(l.closingBalance),
      ]],
      styles: { font: "helvetica", fontSize: 8, cellPadding: 1.8 },
      headStyles: { fillColor: BLACK, textColor: 255, halign: "left" },
      footStyles: { fillColor: LIGHT, textColor: BLACK },
      columnStyles: {
        0: { cellWidth: 22 },
        3: { halign: "right", cellWidth: 30 },
        4: { halign: "right", cellWidth: 30 },
        5: { halign: "right", cellWidth: 30 },
      },
    });
    y = (doc as any).lastAutoTable.finalY + 10;
  }

  footer(doc);
  doc.save(`general-ledger-${dateLabel}.pdf`);
}

export function exportChartOfAccounts(
  accounts: Account[],
  balances: Map<string, number>,
  dateLabel: string
) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const top = header(
    doc,
    "Chart of Accounts",
    `${accounts.length} account${accounts.length === 1 ? "" : "s"} · As of ${dateLabel}`
  );

  // One section row per account type, followed by its accounts.
  const body: any[] = [];
  for (const type of ACCOUNT_TYPES) {
    const items = accounts
      .filter((a) => a.type === type)
      .sort((a, b) => a.code.localeCompare(b.code, undefined, { numeric: true }));
    if (items.length === 0) continue;
    const total = round2(items.reduce((s, a) => s + (balances.get(a.id) ?? 0), 0));
    body.push([
      {
        content: `${ACCOUNT_TYPE_LABELS[type]} (${items.length})`,
        colSpan: 4,
        styles: { fontStyle: "bold", fillColor: LIGHT, textColor: BLACK },
      },
      {
        content: money(total),
        styles: { fontStyle: "bold", fillColor: LIGHT, textColor: BLACK, halign: "right" },
      },
    ]);
    for (const a of items) {
      body.push([
        a.code,
        a.name,
        a.subtype ?? "",
        a.description ?? "",
        money(balances.get(a.id) ?? 0),
      ]);
    }
  }

  autoTable(doc, {
    startY: top,
    head: [["Code", "Account", "Subtype", "Description", "Balance"]],
    body,
    styles: { font: "helvetica", fontSize: 8.5, cellPadding: 2.2, overflow: "linebreak" },
    headStyles: { fillColor: BLACK, textColor: 255, fontStyle: "bold", halign: "left" },
    columnStyles: {
      0: { cellWidth: 18 },
      1: { cellWidth: 42 },
      2: { cellWidth: 30, textColor: GRAY },
      3: { textColor: GRAY },
      4: { halign: "right", cellWidth: 28 },
    },
  });

  footer(doc);
  doc.save(`chart-of-accounts-${dateLabel}.pdf`);
}

export function exportJournal(
  entries: JournalEntry[],
  accounts: Account[],
  dateLabel: string
) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageHeight = doc.internal.pageSize.getHeight();
  const byId = new Map(accounts.map((a) => [a.id, a]));
  const sorted = [...entries].sort((a, b) =>
    a.date !== b.date ? (a.date < b.date ? -1 : 1) : a.createdAt < b.createdAt ? -1 : 1
  );
  const range = sorted.length
    ? `${sorted[0].date} to ${sorted[sorted.length - 1].date}`
    : "No entries";
  let y = header(
    doc,
    "Journal",
    `${sorted.length} entr${sorted.length === 1 ? "y" : "ies"} · ${range}`
  );

  const columnStyles = {
    0: { cellWidth: 18 },
    1: { cellWidth: 55 },
    2: { textColor: GRAY },
    3: { halign: "right" as const, cellWidth: 30 },
    4: { halign: "right" as const, cellWidth: 30 },
  };
  const styles = { font: "helvetica" as const, fontSize: 8.5, cellPadding: 2, overflow: "linebreak" as const };
  const ROW_MM = 7; // approximate row height, used to keep entries on one page

  let grandDebit = 0;
  let grandCredit = 0;
  sorted.forEach((e, i) => {
    // Start a new page rather than splitting an entry across pages.
    const needed = (e.lines.length + 1) * ROW_MM + (i === 0 ? ROW_MM : 0);
    if (i > 0 && y + needed > pageHeight - 20) {
      doc.addPage();
      y = 20;
    }
    const title = [
      `#${i + 1}`,
      e.date,
      e.reference,
      e.description,
      e.isReversal ? "(reversal)" : e.isReversed ? "(reversed)" : "",
    ]
      .filter(Boolean)
      .join("  ·  ");
    const body: any[] = [
      [{ content: title, colSpan: 5, styles: { fontStyle: "bold", fillColor: LIGHT, textColor: BLACK } }],
    ];
    for (const l of e.lines) {
      const a = byId.get(l.accountId);
      grandDebit += l.debit || 0;
      grandCredit += l.credit || 0;
      body.push([
        a?.code ?? "",
        a?.name ?? "(deleted account)",
        l.description ?? "",
        l.debit ? money(l.debit) : "",
        l.credit ? money(l.credit) : "",
      ]);
    }
    autoTable(doc, {
      startY: y,
      // Column headings at the top of each page only.
      head: i === 0 || y === 20 ? [["Code", "Account", "Memo", "Debit", "Credit"]] : undefined,
      body,
      styles,
      headStyles: { fillColor: BLACK, textColor: 255, fontStyle: "bold", halign: "left" },
      columnStyles,
      margin: { left: 14, right: 14 },
      didParseCell: (data) => {
        if (data.section === "head" && data.column.index >= 3) data.cell.styles.halign = "right";
      },
    });
    y = (doc as any).lastAutoTable.finalY + 2;
  });

  // Grand totals at the end only.
  if (y > pageHeight - 30) {
    doc.addPage();
    y = 20;
  }
  autoTable(doc, {
    startY: y + 2,
    body: [[
      { content: "Totals", colSpan: 3, styles: { halign: "right" } },
      money(round2(grandDebit)),
      money(round2(grandCredit)),
    ]],
    styles: { ...styles, fontStyle: "bold", fillColor: LIGHT, textColor: BLACK },
    columnStyles,
    margin: { left: 14, right: 14 },
  });

  footer(doc);
  doc.save(`journal-${dateLabel}.pdf`);
}
